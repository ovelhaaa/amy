"""Bake fixed wordmark artwork, not an embedded font, into LVGL 9.3 A8 masks.
Requires Pillow. No operator image pixels are copied. The font stays local.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter, ImageFont

parser = argparse.ArgumentParser()
parser.add_argument("--font", default="C:/Windows/Fonts/ariali.ttf")
args = parser.parse_args()
scale = 4
font = ImageFont.truetype(args.font, 104 * scale)
parts = []
for name, value, prefix in [("P", "P", ""), ("Four", "4", "P"), ("My", "my", "P4")]:
    canvas = Image.new("L", (320 * scale, 140 * scale))
    ImageDraw.Draw(canvas).text((16 * scale + font.getlength(prefix), -4 * scale), value, font=font, fill=255)
    canvas = canvas.resize((320, 140), Image.Resampling.LANCZOS)
    parts.append((name, canvas, 250, 158))
glow = parts[1][1].filter(ImageFilter.GaussianBlur(8)).point(lambda x: x * 0.65)
parts.insert(0, ("Glow", glow, 250, 158))
credit = Image.new("L", (180 * scale, 30 * scale))
ImageDraw.Draw(credit).text((0, 0), "powered by AMY", font=ImageFont.truetype(args.font, 17 * scale), fill=255)
credit = credit.resize((180, 30), Image.Resampling.LANCZOS)
box = credit.getbbox()
credit = credit.crop(box)
parts.append(("Credit", credit, (800 - credit.width) // 2, 320))
output = ["// Generated by ui-preview/generate_wordmark.py; fixed text artwork only.\n"]
for name, image, x, y in parts:
    box = image.getbbox()
    image = image.crop(box)
    x, y = x + box[0], y + box[1]
    width, height = image.size
    stride = (width + 3) & ~3
    raw = image.tobytes()
    data = b"".join(raw[row * width:(row + 1) * width] + bytes(stride - width) for row in range(height))
    output.append(f"alignas(4) const uint8_t k{name}Data[] = {{\n")
    for start in range(0, len(data), 24):
        output.append("    " + ",".join(str(v) for v in data[start:start+24]) + ",\n")
    output.append("};\n")
    output.append(f"const lv_image_dsc_t k{name}Image=maskDescriptor(k{name}Data,{width},{height},{stride});\n")
    output.append(f"constexpr int k{name}X={x}, k{name}Y={y};\n")
    print(f"{name}: {width}x{height}, stride {stride}, {len(data)} bytes, at {x},{y}")
path = Path(__file__).resolve().parents[1] / "components/ui_blueprint/src/p4my_wordmark.inc"
path.write_text("".join(output), encoding="utf-8")
