"""Generate admission evidence and matrix from completed real-AMY probe logs."""
import hashlib
import json
from pathlib import Path
from audit_patch_library import ROOT, inventory

def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def records(path, tag):
    rows=[]
    for line in path.read_text().splitlines():
        if line.startswith(tag+' '):
            rows.append({k:float(v) if '.' in v else int(v) for k,v in (x.split('=') for x in line.split()[1:])})
    assert len(rows)==768 and len({(r['id'],r['notes']) for r in rows})==768
    return {(r['id'],r['notes']):r for r in rows}

def main():
    base=ROOT/'build/factory010';log=base/'probe.log';obs=base/'observed.log'
    assert 'PASS FACTORY' in log.read_text() and 'PASS FACTORY' in obs.read_text()
    rows=records(log,'FACTORY');observed=records(obs,'OBSERVER')
    timing_path=base/'timing.log';timing={}
    if timing_path.exists():
        assert 'PASS FACTORY timing' in timing_path.read_text()
        for line in timing_path.read_text().splitlines():
            if line.startswith('FACTORY '):
                t={k:float(v) if '.' in v else int(v) for k,v in (x.split('=') for x in line.split()[1:])}
                assert (t['id'],t['notes']) not in timing
                timing[t['id'],t['notes']]=t
        assert len(timing)%3==0

    source,_,entries=inventory()
    result={'schema':1,'rom_sha256':hashlib.sha256(source.encode()).hexdigest(),'evidence':{p.name:sha(p) for p in (log,obs,ROOT/'smk-p4/tests/factory_library_probe.cpp',ROOT/'smk-p4/tests/instrument_factory_audio.py')},'hardware_tested':False,'patches':[]}
    if timing:result['evidence'][timing_path.name]=sha(timing_path)
    matrix=['# Factory library 0.10 — executed host matrix','','Generated by `python smk-p4/tests/summarize_factory_library.py`. Evidence SHA256 is in `factory_library_010_metrics.json`. Fixed-point AMY real engine; timings are desktop observations, never P4 cost classes. Supported means experimental host candidate only.','',
            'Criteria: verified maps/8 voices/zero OOM and guarded render allocations; nonzero PCM in the combined register matrix; zero saturated output and pre-conversion hard clips; release <=2 LSB after 80 simulated seconds for the high-register velocity-127 scenario; observed host max <=5333 us in the original run or a separate timing recheck of IDs pending solely for wall-clock timing. The original matrix was collected during builds and retains all scheduling outliers; the separate recheck has no concurrent firmware build. Both raw maxima remain in JSON. Hardware timing remains pending. Soft-knee samples are reported, not equated with integer overflow. Internal oscillator/filter arithmetic saturation is not exhaustively observable; no DSP algorithm changes or gain compensation.','',
            '|ID|Name|Osc/voice|Load|1/4/8 voices|Raw peak|Master64 peak bound|RMS eight|Saturated|Soft knee|Pre-PCM peak|Host max us|Load us|Heap requested B|Release LSB|Status/reason|','|---|---|---:|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|']
    for i in range(256):
        tests=[dict(rows[i,n],observer=observed[i,n]) for n in (1,4,8)]
        clipped=sum(t['clipped'] for t in tests);hard=sum(t['observer']['hard'] for t in tests)
        release=max(t['release_peak'] for t in tests);peak=max(t['peak'] for t in tests);maximum=max(t['max_us'] for t in tests)
        failures=[]
        if clipped or hard:failures.append('HARD_CLIPPING')
        if release>2:failures.append('RELEASE_TAIL')
        if not peak:failures.append('SILENCE_REVIEW')
        retest=[timing[i,n] for n in (1,4,8)] if (i,1) in timing else []
        if maximum>5333 and (not retest or max(t['max_us'] for t in retest)>5333):failures.append('HOST_DEADLINE_REVIEW')
        if retest and any(t['clipped'] for t in retest) and 'HARD_CLIPPING' not in failures:failures.append('HARD_CLIPPING_RETEST')
        reason=','.join(failures) or 'HOST_CANDIDATE'
        r={'id':i,'supported':not failures,'reason':reason,'tests':tests,'timing_retest':retest};result['patches'].append(r)
        soft=sum(t['observer']['soft'] for t in tests);pre=max(t['observer']['pre_peak'] for t in tests)
        matrix.append(f"|{i}|{entries[i][0]}|{entries[i][1]}|PASS|PASS/PASS/PASS|{peak}|{peak//4}|{tests[-1]['rms']:.2f}|{clipped}|{soft}|{pre}|{maximum}|{tests[0]['load_us']}|{tests[0]['heap']}|{release}|{'AVAILABLE' if not failures else 'FAILED'} {reason}|")
    docs=ROOT/'smk-p4/docs'
    (docs/'factory_library_010_metrics.json').write_text(json.dumps(result,indent=2)+'\n')
    (docs/'factory_library_010_patch_matrix.md').write_text('\n'.join(matrix)+'\n')
    print('Inventoried/tested: 256; admitted:',sum(r['supported'] for r in result['patches']))

if __name__=='__main__':main()
