"""Offline ROM metadata generator. No boot-time parsing or instrument allocation."""
import argparse
import hashlib
import json
import re
from pathlib import Path
from audit_patch_library import inventory, ROOT

OUT = ROOT / 'smk-p4/components/amy_runtime'
LEGACY = [128,135,138,142,4,31,32,8,0,1,12,14,131,141,144,151]

def category(name):
    n = name.upper()
    for cat, words in [('ElectricPiano',['E.PIANO','ELECT. PIANO','E PIANO']),('Piano',['PIANO']),('Organ',['ORGAN','OWGAN','CALLIOPE']),('Bass',['BASS']),('Brass',['BRASS','TRUMP','HORN','FANFARE','TROMB']),('Strings',['STRING','VIOL','CELLO','CHOIR']),('Pads',['PAD','SWELL']),('Leads',['LEAD','SOLO']),('Plucks',['PLUCK','GUIT','KOTO','HARP','PIZZ','CLAV','SITAR','BANJO']),('Percussion',['DRUM','PERC','BELL','CHIME','XYLO','VIBE','MARIM','GONG','STEEL','TIMP','CELEST'])]:
        if any(w in n for w in words): return cat
    return 'FX'

def products():
    source, costs, entries = inventory()
    matches=list(re.finditer(r'/\* (\d+): (.*?) \*/ "(.*?)",',source))
    factory_matches=[m for m in matches if int(m[1])<256]
    assert len(factory_matches)==256 and len({int(m[1]) for m in factory_matches})==256, 'Duplicate/missing factory IDs'
    raw = {int(m[1]):m[3] for m in matches}
    assert len(entries)==266 and len(costs)==391
    assert all(i in entries and entries[i][0] for i in range(256))
    results_path=ROOT/'smk-p4/docs/factory_library_010_metrics.json'
    results=json.loads(results_path.read_text()) if results_path.exists() else None
    rom_hash=hashlib.sha256(source.encode()).hexdigest()
    if results: assert results['rom_sha256']==rom_hash, 'ROM changed; rerun qualification'
    lines=['// Generated by generate_factory_library.py; do not edit.',f'// ROM SHA256 {rom_hash}','inline constexpr Patch kFactory[] = {']
    ui=['// Generated; included inside constexpr BlueprintPatchEntry array.']
    admitted=[]
    inv=['# Factory library 0.10 inventory','',f'ROM SHA256 `{rom_hash}`. 256 Juno/DX7 IDs; 391 total positions, 266 populated, 125 reserved.','',
         'Names and costs come directly from ROM. Categories are deterministic name heuristics (FX is the fallback), not historical factory classifications. Juno bank A/B is explicit in ROM names; DX7 source bank is recorded as AMY DX7: amy/headers.py uses fm.DX7Patch.from_patch_number, and amy/fm.py reads sequential156-byte records from default-dx7-patches.bin (dx7db/learnfm). This does not establish historical ROM1–4 provenance. No invented historical bank mapping.','',
         'Memory requires oscillator/filter state, eight instrument/FIFO maps and shared delta storage; actual requested bytes are in the generated qualification matrix. FX disabled: chorus requests are ignored, factory EQ retained. Mono/unison in a name does not force monophony: eight independent gates remain. All rows are ROM_PRESENT; host/support/failure states are separate flags.','',
         '|ID|Original name|Family|Category|Bank|Osc/voice|Filters|Effects/global|Command letters|Structure|','|---|---|---|---|---|---:|---|---|---|---|']
    for i in range(256):
        name,cost,family,*_=entries[i]
        cmd=raw[i]; fam='Subtractive' if i<128 else 'FM'
        assert family==('subtractive' if i<128 else 'FM'), (i,family)
        assert set(re.findall(r'[A-Za-z]',cmd)) <= set('ABFGILOPRZabcdfkmovwx'), 'Unreviewed ROM command'
        assert not any(token in cmd for token in ('ic','io')), 'Embedded instrument/mapping command'
        assert cost==(6 if i<128 else 8)
        refs=[int(x) for x in re.findall(r'(?:v|c|L|m)(\d+)',cmd)]
        # L is a modulation target selector, m is a local oscillator source.
        assert all(x<cost for x in refs), (i,refs)
        if i>=128:
            for ops in re.findall(r'O([\d,]+)',cmd):
                assert all(int(x)<cost for x in ops.split(',') if x)
        bank=('JUNO A' if i<64 else 'JUNO B') if i<128 else 'AMY DX7'
        status=1; reason='NOT RUN'
        if results:
            r=results['patches'][i]; assert r['id']==i
            status |= 2
            if r['supported']: status |= 4; admitted.append(i)
            else: status |= 16 | 8; reason=r['reason']
        elif i in LEGACY and i!=32: status |= 4; admitted.append(i)
        cat=category(name)
        lines.append(f'    {{{i},{json.dumps(name)},{cost},SynthFamily::{fam},PatchCategory::{cat},{json.dumps(bank)},{status}}},')
        ui.append(f'    {{{i},library::kFactory[{i}].name,library::kFactory[{i}].bank,library::kFactory[{i}].category,library::kFactory[{i}].family,FeatureStatus::{"Available" if status&4 else "Unavailable" if status&16 else "Planned"},false,{{"CHAR","BRIGHT","MOTION","SHAPE","ATK","REL","SPACE","DRIVE"}}}},')
        letters=''.join(sorted(set(re.findall(r'[A-Za-z]',cmd))))
        inv.append(f'|{i}|{name}|{fam}|{cat}|{bank}|{cost}|{"LPF24 G4" if "G4" in cmd else "none"}|{"EQ/chorus dry" if "x" in cmd or "k" in cmd else "none"}|{letters}|local references within voice; {reason}|')
    lines+=['};']
    supported=['// Generated admission list; constant metadata only.']+[f'    library::kFactory[{i}],' for i in [128]+[i for i in admitted if i!=128]]
    return {OUT/'factory_catalog.inc':'\n'.join(lines)+'\n',OUT/'factory_supported.inc':'\n'.join(supported)+'\n',OUT/'factory_ui.inc':'\n'.join(ui)+'\n',ROOT/'smk-p4/docs/factory_library_010_inventory.md':'\n'.join(inv)+'\n'}

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,data in products().items():
        if a.check: assert path.read_text(encoding='utf-8')==data, f'Stale {path}'
        elif not path.exists() or path.read_text(encoding='utf-8')!=data: path.write_text(data,encoding='utf-8')
