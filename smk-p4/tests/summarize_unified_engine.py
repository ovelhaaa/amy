"""Generate the0.8 qualification matrix from executed host evidence, not ROM existence."""
import hashlib
import json
import re
import wave
from pathlib import Path
from audit_patch_library import inventory, ROOT


def main():
    build = ROOT / "build/unified08"
    paths = [build / name for name in ("probe.log", "runtime.log", "candidates.log", "ui.log")]
    probe, runtime, candidates, ui = [p.read_text(encoding="utf-8") for p in paths]
    assert "PASS isolated" in probe and "PASS runtime reuse" in runtime and "PASS unified live adapter" in ui
    _, costs, rom = inventory()
    ids = (128, 135, 138, 142, 131, 141, 144, 151, 4, 8, 12, 14, 31, 0, 1, 32)
    rows = []
    wav_hashes = set()
    for ident in ids:
        dry = [dict(zip(("notes", "peak", "rms", "clipped", "avg_us", "max_us"), m))
               for m in re.findall(rf"DRY_HOST patch={ident} notes=(\d+) peak=(\d+) rms=([\d.]+) clipped=(\d+) avg_us=(\d+) max_us=(\d+)", candidates)]
        assert {int(r["notes"]) for r in dry} == {1, 4, 6, 8}
        reusable = [dict(zip(("notes", "peak", "avg_us", "max_us"), map(int, m)))
                    for m in re.findall(rf"REUSABLE_HOST patch={ident} notes=(\d+) peak=(\d+) render_avg_us=(\d+) render_max_us=(\d+) clipped=0", runtime)]
        admitted = ident != 32
        assert not admitted or {r["notes"] for r in reusable} == {1, 4, 8}
        tail = [int(m) for m in re.findall(rf"RELEASE_HOST patch={ident} notes=\d+ tail_peak=(\d+)", runtime)]
        assert not admitted or len(tail) == 3 and max(tail) <= 2
        if admitted:
            assert all(int(r["clipped"]) == 0 for r in dry)
            assert (build / f"patch_{ident}_8.wav").is_file()
            wav_path = build / f"patch_{ident}_8.wav"
            with wave.open(str(wav_path), "rb") as wav:
                assert (wav.getframerate(), wav.getnchannels(), wav.getsampwidth(), wav.getnframes()) == (48000, 2, 2, 65536)
            wav_hashes.add(hashlib.sha256(wav_path.read_bytes()).hexdigest())
        else:
            assert any(int(r["clipped"]) > 0 for r in dry)
        rows.append({"id": ident, "rom_name": rom[ident][0], "oscillators_per_voice": costs[ident],
                     "family": rom[ident][2], "dry_fresh_engine": dry, "reusable": reusable,
                     "release_tail_peak": max(tail) if tail else None,
                     "software_candidate": admitted, "hardware_qualified": False})
    evidence = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}
    assert len(wav_hashes) == 15, "Audition PCM must differ between candidates"
    report = {"schema_version": 1, "host_only": True, "voices": 8, "oscillator_capacity": 64,
              "resident_instruments": 8, "evidence_sha256": evidence, "patches": rows}
    (ROOT / "smk-p4/docs/unified_engine_08_host_metrics.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    lines = ["# Patch matrix0.8", "", "Generated by `python smk-p4/tests/summarize_unified_engine.py` from executed logs.",
             "16 ROM candidates evaluated;15 software candidates exposed in the opt-in firmware. No patch is physically qualified for0.8.",
             "256 ROM IDs are catalog potential only, not an AVAILABLE claim. Existing0.7 inventory describes the wider ROM.", "",
             "|ID|ROM name|Family|Osc/voice|Fresh host1/4/6/8|Reusable1/4/8|Firmware0.8|Physical0.8|", "|---|---|---|---:|---|---|---|---|"]
    for row in rows:
        good = row["software_candidate"]
        lines.append(f"|{row['id']}|{row['rom_name']}|{row['family']}|{row['oscillators_per_voice']}|{'PASS' if good else 'FAIL clipping at8'}|{'PASS' if good else 'NOT RUN; excluded'}|{'Software candidate' if good else 'Unavailable'}|MANUAL|")
    lines += ["", "Fresh tests render ROM PCM before Runtime master gain: Juno32 clipped144 samples in the eight-note workload, so master reduction is not used as a workaround.",
              "Reusable tests include full preset materialization, allocator-guarded rendering, raw clipping counters, release and Panic. PCM WAVs retain the existing master setting; no normalization.",
              "Juno14 eight-note release leaves one output LSB after80 seconds of simulated release; the automated threshold is two LSBs (below-84dBFS), not a claim of mathematically exact silence. Other tested tails were zero.",
              "ROM EQ is retained for Juno and neutralized before subsequent loads. Chorus/reverb/echo remain disabled. Basic dry timbre is tested; S3's macro/envelope/mono/FX overrides are not copied and sonic equivalence is NOT claimed.",
              "Flute is grouped under the existing FX browser category because Blueprint1.1 has no wind category; its canonical ROM name and FM family are preserved.", ""]
    (ROOT / "smk-p4/docs/unified_engine_08_patch_matrix.md").write_text("\n".join(lines), encoding="utf-8")
    print("PASS evidence-consistent matrix:16 evaluated,15 software candidates,0 physically qualified")


if __name__ == "__main__":
    main()
