"""Summarize measured output, preserving the host/target distinction."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def records(text, prefix):
    return [dict(re.findall(r"(\w+)=([^\s]+)", line)) for line in text.splitlines() if line.startswith(prefix)]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--log", type=Path, default=ROOT / "build/library8_verified07.log")
    parser.add_argument("--quiet-log", type=Path)
    parser.add_argument("--quiet-probe-log", type=Path)
    args = parser.parse_args()
    text = args.log.read_text(encoding="utf-8")
    probe = args.quiet_probe_log.read_text(encoding="utf-8") if args.quiet_probe_log else text
    runtime = args.quiet_log.read_text(encoding="utf-8") if args.quiet_log else text
    data = {"platform": "HOST x86-64; not P4 timing/memory", "physical_qualification": "NOT RUN",
            "source_log": str(args.log), "quiet_probe_log": str(args.quiet_probe_log) if args.quiet_probe_log else None, "quiet_runtime_log": str(args.quiet_log) if args.quiet_log else None,
            "bank_measurements": records(probe,"BANK "), "replacements": records(probe,"REPLACE "),
            "dry_render": records(probe,"DRY_HOST "), "candidate_heap": records(probe,"CANDIDATE "),
            "runtime_scenes": records(runtime,"HOST "), "ram_self_test": records(text,"RAM_SELF_TEST ")}
    assert len(data["dry_render"]) == 48 and len(data["candidate_heap"]) == 12
    out = ROOT / "build/sound_library_07_metrics.json"
    out.write_text(json.dumps(data,indent=2) + "\n", encoding="utf-8")
    resident = sorted({int(r["patch"]) for r in data["ram_self_test"]})
    lines = ["# SMK-P4 0.7 — medições host", "", "Generated by `python smk-p4/tests/summarize_sound_library.py`. Source: `" + args.log.name + "`.", "", "Dry probe: one eight-instrument bank,64 oscillator capacity, no runtime master,256 blocks per note count, notes48+3*i,velocity100. Each candidate ran1/4/6/8 notes. Heap includes shared engine/pool; it is NOT incremental bank cost or P4 internal RAM. No new FX. Musical/auditory/physical acceptance remains MANUAL.", "", "|Patch|Osc/voice (measured)|Single-bank host heap B|8-note peak|RMS|Clipped samples|Dry render avg/max us|Status in firmware candidate|", "|---|---:|---:|---:|---:|---:|---|---|"]
    for heap in data["candidate_heap"]:
        ident = heap["patch"]
        r = next(r for r in data["dry_render"] if r["patch"]==ident and r["notes"]=="8")
        status = "software resident; hardware NOT RUN" if int(ident) in resident else "PLANNED; not selectable"
        if int(r["clipped"]): status = "FAIL dry clipping; not selectable"
        lines.append(f'|{ident}|{heap["oscs"]}|{heap["heap"]}|{r["peak"]}|{r["rms"]}|{r["clipped"]}|{r["avg_us"]}/{r["max_us"]}|{status}|')
    lines += ["", "Raw bank materialization (before runtime service reserve):", "", "|Banks|Patch|Incremental host heap B|Alloc calls|Load us|Total live B|", "|---|---|---:|---:|---:|---:|"]
    for r in data["bank_measurements"]:
        lines.append(f'|{r["banks"]}|{r["patch"]}|{r["heap_delta"]}|{r["alloc_calls"]}|{r["load_us"]}|{r["total_bytes"]}|')
    lines += ["", "Replacement allocated24 times per eight-voice FM bank at every tested capacity; see JSON. This is not an allocation-free transition and does not prove rollback safety.", "", "Four-resident-bank runtime (all musical scenarios assert eight admitted voices and no service heap):", "", "|Patch|Full render avg/max us|Worst scene render us|Worst apply+render us|", "|---|---|---:|---:|"]
    for ident in resident:
        scenes = [r for r in data["runtime_scenes"] if int(r["patch"])==ident]
        full = next(r for r in scenes if r["scene"]=="full")
        lines.append(f'|{ident}|{full["render_avg_us"]}/{full["render_max_us"]}|{max(int(r["render_max_us"]) for r in scenes)}|{max(int(r["service_max_us"]) for r in scenes)}|')
    lines += ["", "Runtime timing source: " + (args.quiet_log.name + " (no concurrent Codex builds)" if args.quiet_log else "concurrent compilation; scheduler-contaminated maxima"), ("Raw dry/load timing source: " + args.quiet_probe_log.name + " (no concurrent Codex builds). These are not target deadline or latency claims." if args.quiet_probe_log else "Raw dry/load timings were collected under concurrent compilation. These are not target deadline or latency claims.") + " This host matrix does not include target measurements; see sound_library_07_hardware_qualification.md for actual startup data. CPU total, DMA underruns and physical latency remain unmeasured. The target block budget remains5333.33us.", ""]
    (ROOT / "smk-p4/docs/sound_library_07_benchmark.md").write_text("\n".join(lines),encoding="utf-8")
    print("PASS generated measured host matrix; target/audition MANUAL")

if __name__ == "__main__":
    main()
