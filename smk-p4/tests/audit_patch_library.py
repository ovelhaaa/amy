"""Reproducible static audit; resource eligibility is not musical qualification."""
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def inventory():
    source = (ROOT / "src/patches.h").read_text(encoding="utf-8")
    costs = [int(x) for x in re.search(r"patch_oscs.*?=\s*\{(.*?)\};", source, re.S)[1].split(",") if x.strip()]
    entries = {}
    for match in re.finditer(r'/\* (\d+): (.*?) \*/ "(.*?)",', source):
        ident, name, commands = int(match[1]), match[2].strip(), match[3]
        waves = sorted(set(map(int, re.findall(r"w(\d+)", commands))))
        family = "PCM" if 7 in waves else "partials" if any(w in waves for w in (9,10,11)) else "FM" if 8 in waves else "subtractive"
        algorithms = "/".join(re.findall(r"o(\d+)", commands)) or "-"
        eligibility = "resource candidate; not qualified"
        if family == "partials": eligibility = "BLOCKED: partials disabled"
        if "ic" in commands or "io" in commands: eligibility = "BLOCKED: embedded MIDI mappings/drum configuration outside adapter contract"
        entries[ident] = (name, costs[ident], family, algorithms, waves, "LPF24 (G4)" if "G4" in commands else "cutoff; default type" if "F" in commands else "no", "chorus/EQ request (disabled/global)" if "k" in commands or "x" in commands else "none", eligibility)
    assert len(costs) == 391
    return source, costs, entries

def report():
    source, costs, entries = inventory()
    lines = ["# SMK-P4 0.7 — inventário AMY", "", "Generated by `python smk-p4/tests/audit_patch_library.py`; source SHA256 (UTF-8/LF normalized) `" + hashlib.sha256(source.encode()).hexdigest() + "`.", "", "391 table positions contain 266 populated commands and 125 reserved slots (259–383), not 391 loadable sounds. NULL/reserved positions are explicitly rejected. Classification follows wave commands, not instrument names. Juno 17 is subtractive, not PCM.", "", "FM: six operators, one ALGO parent and one LFO (8 oscillators/voice). Juno: filtered parent, LFO, pulse, saw, sub and noise (6/voice). `patch_oscs` is admission cost, not necessarily the highest oscillator referenced by embedded drum mappings. Algorithms are AMY wire indices. All wave IDs below come from the actual command string.", "", "Memory: oscillator state/filter state plus instrument/FIFO/maps and shared delta pool. Per-patch heap and DSP require the executable probe; static ROM strings do not imply resident instruments. PCM requires baked sample data; partials are disabled in the standalone configuration. Chorus/reverb/echo stay disabled; factory EQ/chorus commands require an explicit compatibility decision, even where a dry patch renders. No new effects are enabled.", "", "Architectures: A materializes every selected instrument at boot and selects only resident banks. B calls instrument_prepare (three heap allocations/instrument), frees old FIFOs/instrument, parses strings and may allocate DSP state/deltas. Checked admission ends before materialization and is not a complete rollback transaction. B is rejected for the audio service in 0.7. See executable measurements and decision in sound_library_07_results.md.", "", "Baseline two FM banks: 16 instruments /128 oscillators at eight voices. Four FM banks:32/256. Four FM plus two Juno banks:48/352. Each bank remains eight voices; no dynamic polyphony reduction. Extra memory must pass both boot and post-boot reserves; host times cannot qualify P4 deadlines.", "", "|ID|Original name|Osc/voice|Family|Operators|Algorithm|Wave IDs|Filter|Aux/effects request|Eligibility|", "|---|---|---:|---|---:|---|---|---|---|---|"]
    for ident, cost in enumerate(costs):
        if ident not in entries:
            lines.append(f"|{ident}|NULL/reserved|{cost}|none|0|-|-|no|none|BLOCKED|")
        else:
            name, cost, family, algorithms, waves, filt, effects, eligible = entries[ident]
            lines.append(f"|{ident}|{name}|{cost}|{family}|{6 if family == 'FM' else 0}|{algorithms}|{','.join(map(str,waves))}|{filt}|{effects}|{eligible}|")
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "smk-p4/docs/patch_library_inventory_07.md"
    if args.check:
        assert path.read_text(encoding="utf-8") == report(), "Inventory is stale"
    else:
        path.write_text(report(), encoding="utf-8")
