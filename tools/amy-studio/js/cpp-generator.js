/**
 * AMY Studio - C++ Factory Patch Table Code Generator
 * Translates active web patches into the exact C++ PatchDescriptor struct array
 * used by components/synth/src/factory_patches.cpp on the ESP32-S3 firmware.
 */

class CppPatchTableGenerator {
  constructor() {}

  generateCppCode(patches = null) {
    const list = patches || AMY_FACTORY_PATCHES;
    const lines = [];

    lines.push(`// =======================================================================================`);
    lines.push(`// Auto-generated by AMY Studio Web Workstation`);
    lines.push(`// Target: ESP32-S3 DevKitC (SMK-S3 Synthesizer Firmware)`);
    lines.push(`// Date: ${new Date().toISOString()}`);
    lines.push(`// Total Patches: ${list.length}`);
    lines.push(`// =======================================================================================`);
    lines.push(``);
    lines.push(`#include "factory_patches.h"`);
    lines.push(`#include <cstring>`);
    lines.push(``);
    lines.push(`namespace smk {`);
    lines.push(``);
    lines.push(`uint32_t calculatePatchCrc32(const SynthPatch& patch) {`);
    lines.push(`    const uint8_t* p = reinterpret_cast<const uint8_t*>(&patch);`);
    lines.push(`    size_t len = sizeof(SynthPatch) - sizeof(uint32_t); // Exclude the crc32 field itself`);
    lines.push(`    `);
    lines.push(`    uint32_t crc = 0xFFFFFFFF;`);
    lines.push(`    for (size_t i = 0; i < len; ++i) {`);
    lines.push(`        crc ^= p[i];`);
    lines.push(`        for (int j = 0; j < 8; ++j) {`);
    lines.push(`            crc = (crc >> 1) ^ (0xEDB88320 & (-(crc & 1)));`);
    lines.push(`        }`);
    lines.push(`    }`);
    lines.push(`    return ~crc;`);
    lines.push(`}`);
    lines.push(``);
    lines.push(`struct PatchDescriptor {`);
    lines.push(`    uint8_t     id;`);
    lines.push(`    const char* name;`);
    lines.push(`    const char* category;`);
    lines.push(`    const char* author;`);
    lines.push(`    uint16_t    engine_patch;`);
    lines.push(`    uint8_t     wave_type;    // 0=SINE, 1=SAW, 3=TRI, 4=SQR, 7=PCM, 8=ALGO/FM`);
    lines.push(`    int8_t      transpose;`);
    lines.push(`    uint8_t     voice_count;`);
    lines.push(`    float       filter_cutoff;`);
    lines.push(`    float       filter_res;`);
    lines.push(`    float       amp_attack;`);
    lines.push(`    float       amp_decay;`);
    lines.push(`    float       amp_sustain;`);
    lines.push(`    float       amp_release;`);
    lines.push(`};`);
    lines.push(``);
    lines.push(`static const PatchDescriptor s_patch_table[FactoryPatches::kCount] = {`);

    list.forEach((p, idx) => {
      const id = p.id !== undefined ? p.id : idx;
      const name = (p.name || `Patch ${id}`).padEnd(24, ' ').substring(0, 24);
      const cat = (p.category || 'SYNTH').padEnd(14, ' ').substring(0, 14);
      const author = (p.author || 'AMY STUDIO').padEnd(12, ' ').substring(0, 12);
      const enginePatch = p.basePatch !== undefined ? p.basePatch : (p.engine_patch || id);
      const waveType = p.wave_type !== undefined ? p.wave_type : (p.type === 'DX7' ? 8 : (p.type === 'PCM/GM' ? 7 : 1));
      const transpose = p.transpose || 0;
      const voices = p.voice_count || 8;
      const cutoff = (p.filter_cutoff || 3500.0).toFixed(1) + 'f';
      const res = (p.filter_res || 1.0).toFixed(1) + 'f';
      const atk = (p.amp_attack || 10.0).toFixed(1) + 'f';
      const dec = (p.amp_decay || 250.0).toFixed(1) + 'f';
      const sus = (p.amp_sustain !== undefined ? p.amp_sustain : 0.8).toFixed(2) + 'f';
      const rel = (p.amp_release || 300.0).toFixed(1) + 'f';

      const padId = String(id).padStart(3, ' ');
      const padEngine = String(enginePatch).padStart(3, ' ');
      const padTrans = String(transpose).padStart(3, ' ');
      const padVoices = String(voices).padStart(2, ' ');

      lines.push(`    { ${padId}, "${name}", "${cat}", "${author}", ${padEngine}, ${waveType}, ${padTrans}, ${padVoices}, ${cutoff.padStart(8, ' ')}, ${res.padStart(5, ' ')}, ${atk.padStart(6, ' ')}, ${dec.padStart(7, ' ')}, ${sus.padStart(5, ' ')}, ${rel.padStart(7, ' ')} }${idx < list.length - 1 ? ',' : ''}`);
    });

    lines.push(`};`);
    lines.push(``);
    lines.push(`const SynthPatch* FactoryPatches::getPatchById(uint8_t patch_id) {`);
    lines.push(`    for (size_t i = 0; i < kCount; ++i) {`);
    lines.push(`        if (s_patch_table[i].id == patch_id) {`);
    lines.push(`            return getPatchByIndex(i);`);
    lines.push(`        }`);
    lines.push(`    }`);
    lines.push(`    return getPatchByIndex(0);`);
    lines.push(`}`);
    lines.push(``);
    lines.push(`const SynthPatch* FactoryPatches::getPatchByIndex(size_t index) {`);
    lines.push(`    if (index >= kCount) return nullptr;`);
    lines.push(`    static SynthPatch patch;`);
    lines.push(`    const auto& d = s_patch_table[index];`);
    lines.push(`    patch.id = d.id;`);
    lines.push(`    strncpy(patch.name, d.name, sizeof(patch.name) - 1);`);
    lines.push(`    strncpy(patch.category, d.category, sizeof(patch.category) - 1);`);
    lines.push(`    strncpy(patch.author, d.author, sizeof(patch.author) - 1);`);
    lines.push(`    patch.engine_patch = d.engine_patch;`);
    lines.push(`    patch.wave_type = d.wave_type;`);
    lines.push(`    patch.transpose = d.transpose;`);
    lines.push(`    patch.voice_count = d.voice_count;`);
    lines.push(`    patch.base_freq = 440.0f;`);
    lines.push(`    patch.filter_cutoff = d.filter_cutoff;`);
    lines.push(`    patch.filter_res = d.filter_res;`);
    lines.push(`    patch.amp_attack = d.amp_attack;`);
    lines.push(`    patch.amp_decay = d.amp_decay;`);
    lines.push(`    patch.amp_sustain = d.amp_sustain;`);
    lines.push(`    patch.amp_release = d.amp_release;`);
    lines.push(`    patch.crc32 = calculatePatchCrc32(patch);`);
    lines.push(`    return &patch;`);
    lines.push(`}`);
    lines.push(``);
    lines.push(`} // namespace smk`);

    return lines.join('\n');
  }

  downloadCppFile() {
    const code = this.generateCppCode();
    const blob = new Blob([code], { type: 'text/x-c++src;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'factory_patches.cpp';
    a.click();
    URL.revokeObjectURL(url);
    console.log("[C++ Generator] factory_patches.cpp downloaded successfully.");
  }

  async copyToClipboard() {
    const code = this.generateCppCode();
    await navigator.clipboard.writeText(code);
    alert("Código C++ copiado para a área de transferência com sucesso!");
  }
}

window.cppPatchTableGenerator = new CppPatchTableGenerator();
